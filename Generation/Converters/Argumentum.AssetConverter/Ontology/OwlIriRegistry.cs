            throw new InvalidOperationException(
                $"[OwlIriRegistry/{corpus}] no pinned IRI for pk '{pk}' (the English label would mint " +
                $"'{labelDerivedFragment}'). Extend the registry dictionaries in the same reviewed diff — " +
                "since P24-34 an English label never mints a served IRI (#133).");
        }
