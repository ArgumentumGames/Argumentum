        /// <summary>
        /// Resolve the pinned fragment for a corpus row, or refuse loudly. The refusal names the
        /// pk and the fragment the label would have minted: that message IS the extension
        /// procedure — an unpinned row must extend the dictionaries in the same reviewed diff.
        /// </summary>
        internal static string ResolvePinnedFragment(string corpus, IReadOnlyDictionary<string, string> pins,
            string pk, string labelDerivedFragment)
        {
            if (pins.TryGetValue(pk, out var pinned))
            {
                return pinned;
